// Generates src/index.ts: every primitive (default export → named), every atom,
// the provider, utils, and all exported types. Type names that collide across
// files get a file-name prefix (e.g. CodeBlock's DiffRow → CodeBlockDiffRow).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../src/", import.meta.url));
const groups = [
  ["atoms", false],
  ["primitives", true],
  ["provider", false],
];

const files = [];
for (const [dir, hasDefault] of groups) {
  for (const f of readdirSync(join(root, dir)).filter((f) => f.endsWith(".tsx")).sort()) {
    const name = f.replace(/\.tsx$/, "");
    const code = readFileSync(join(root, dir, f), "utf8");
    const values = [...code.matchAll(/^export (?:const|function) (\w+)/gm)].map((m) => m[1]);
    const types = [...code.matchAll(/^export (?:type|interface) (\w+)/gm)].map((m) => m[1]);
    const inlineTypes = [...code.matchAll(/^export \{[^}]*\}/gm)].flatMap((m) =>
      m[0].replace(/export \{|\}/g, "").split(",").map((s) => s.trim()).filter(Boolean),
    );
    files.push({ dir, name, hasDefault: hasDefault && /^export default function/m.test(code), values: [...values, ...inlineTypes], types });
  }
}

const typeCount = {};
for (const f of files) for (const t of f.types) typeCount[t] = (typeCount[t] || 0) + 1;
const valueNames = new Set(files.flatMap((f) => [...f.values, ...(f.hasDefault ? [f.name] : [])]));

let out = "/* AUTO-GENERATED by scripts/make-index.mjs — do not edit by hand. */\n";
for (const f of files) {
  const path = `./${f.dir}/${f.name}`;
  const vals = [...(f.hasDefault ? [`default as ${f.name}`] : []), ...f.values];
  if (vals.length) out += `export { ${vals.join(", ")} } from "${path}";\n`;
  const types = f.types.map((t) => (typeCount[t] > 1 || valueNames.has(t) ? `${t} as ${f.name}${t}` : t));
  if (types.length) out += `export type { ${types.join(", ")} } from "${path}";\n`;
}
out += `export { cn } from "./lib/utils";\n`;
writeFileSync(join(root, "index.ts"), out);
const renamed = Object.entries(typeCount).filter(([, n]) => n > 1).map(([t]) => t);
console.log(`index.ts: ${files.length} modules; prefixed duplicate types: ${renamed.join(", ") || "none"}`);
